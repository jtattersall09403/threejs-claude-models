  // in the first two segments and finishes near the ankles, so gravity is legible.
// CRITIC 11: swung further BACK and clear of the leg line. Hanging as a thin near-
  // vertical rope from hip height it overlapped the legs from az 60-180 and silhouetted
  // as a third limb.
// Swinging it clear of the legs must not turn it back into a RUDDER. Reaching 0.51 m
  // behind while only dropping to y 0.262 put it out near-horizontal at hip height — the
