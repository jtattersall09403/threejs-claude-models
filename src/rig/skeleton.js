// Rest-pose skeleton. Everything downstream (SDF anatomy, clothing, skin weights)
// reads positions from here, so proportions are changed in exactly one place.
// Space: metres, Y up, character faces +Z. Feet on y = 0.
import * as THREE from 'three';

const L = 1, R = -1;

/**
 * The tail spine, from root to tip.
 *
 * Exported because parts/anatomy.js builds the tail's capsules from these SAME
 * points. Held separately in both files they drifted — the bones said one thing and
 * the geometry another — which skins the tail to the wrong spans and deforms it
 * incorrectly the moment it is animated. One definition, imported.
 */
export const TAIL_SPINE = [
  // The z-steps shrink while the y-steps stay even, so the tail leaves the hip
  // travelling backwards and progressively turns downward. Even steps in both give a
  // constant angle, which reads as a rigid plank bolted to the pelvis.
  // It has to HANG. Reaching 0.50 m behind the hips while only dropping to y 0.305, the
  // tail left the body at a shallow angle and read from the side as a rudder bolted to
  // the pelvis — the single most rigid thing in the silhouette. Now it turns down hard
  // in the first two segments and finishes near the ankles, so gravity is legible.
  [0, 0.930, -0.120],
  [0, 0.830, -0.238],
  [0, 0.690, -0.322],
  [0, 0.530, -0.372],
  [0, 0.370, -0.386],
  [0, 0.215, -0.352],
];

// name -> { parent, pos }.  `.L`/`.R` pairs are generated by mirror().
